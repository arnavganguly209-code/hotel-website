/**
 * Appends HBL PACO UAT credentials from the official PHP SDK SecurityData.php
 * and 2c2papiint.txt into .env (gitignored). Does not print secrets.
 *
 * Usage:
 *   node scripts/setup-hbl-paco-env.mjs
 *   node scripts/setup-hbl-paco-env.mjs --sdk "C:/path/to/SecurityData.php" --notes "C:/path/to/2c2papiint.txt"
 */
import fs from "fs";
import path from "path";

const root = process.cwd();
const envPath = path.join(root, ".env");

function extractStaticString(source, name) {
  const re = new RegExp(
    `public\\s+static\\s+string\\s+\\$${name}\\s*=\\s*"([\\s\\S]*?)";`,
    "m"
  );
  const m = source.match(re);
  if (!m) return null;
  return m[1].replace(/\s+/g, "");
}

function parseNotes(text) {
  const office =
    text.match(/merchant_id\/officeid\s*:\s*(\d+)/i)?.[1] ||
    text.match(/officeid\s*[:=]\s*(\d+)/i)?.[1];
  const api =
    text.match(/api_key\s*=\s*"([^"]+)"/i)?.[1] ||
    text.match(/api_key\s*[:=]\s*"?([a-f0-9]+)"?/i)?.[1];
  return { officeId: office || "", apiKey: api || "" };
}

const sdkDefault = path.join(
  root,
  "tmp",
  "hbl",
  "hbldemo",
  "hbldemo",
  "src",
  "SecurityData.php"
);
const notesDefault = path.join(root, "tmp", "hbl", "2c2papiint.txt");
const notesAlt = "C:/Users/Admin/Desktop/PACO/2c2papiint.txt";
const sdkAlt = path.join(
  root,
  "tmp",
  "hbl",
  "hbldemo",
  "hbldemo",
  "src",
  "SecurityData.php"
);

const args = process.argv.slice(2);
function argValue(flag) {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : null;
}

const sdkPath = argValue("--sdk") || (fs.existsSync(sdkDefault) ? sdkDefault : sdkAlt);
const notesPath =
  argValue("--notes") ||
  (fs.existsSync(notesDefault)
    ? notesDefault
    : fs.existsSync(notesAlt)
      ? notesAlt
      : notesDefault);

if (!fs.existsSync(sdkPath)) {
  console.error("SecurityData.php not found:", sdkPath);
  process.exit(1);
}

const sdk = fs.readFileSync(sdkPath, "utf8");
const encryptionKeyId = extractStaticString(sdk, "EncryptionKeyId");
const accessToken = extractStaticString(sdk, "AccessToken");
const signing = extractStaticString(sdk, "MerchantSigningPrivateKey");
const pacoEnc = extractStaticString(sdk, "PacoEncryptionPublicKey");
const pacoSign = extractStaticString(sdk, "PacoSigningPublicKey");
const decrypt = extractStaticString(sdk, "MerchantDecryptionPrivateKey");

if (!signing || !pacoEnc || !pacoSign || !decrypt || !encryptionKeyId) {
  console.error("Failed to extract one or more keys from SecurityData.php");
  process.exit(1);
}

let officeId = "";
let apiKey = accessToken || "";
if (fs.existsSync(notesPath)) {
  const notes = parseNotes(fs.readFileSync(notesPath, "utf8"));
  officeId = notes.officeId || officeId;
  apiKey = notes.apiKey || apiKey;
}

const block = `
# --- HBL PACO (generated by scripts/setup-hbl-paco-env.mjs) ---
HBL_PACO_ENV=uat
HBL_PACO_OFFICE_ID=${officeId}
HBL_PACO_API_KEY=${apiKey}
HBL_PACO_ENCRYPTION_KEY_ID=${encryptionKeyId}
HBL_PACO_BASE_URL=https://core.demo-paco.2c2p.com/
HBL_PACO_REQUEST_3DS=Y
HBL_PACO_CURRENCY=USD
HBL_PACO_MERCHANT_SIGNING_PRIVATE_KEY=${signing}
HBL_PACO_PACO_ENCRYPTION_PUBLIC_KEY=${pacoEnc}
HBL_PACO_PACO_SIGNING_PUBLIC_KEY=${pacoSign}
HBL_PACO_MERCHANT_DECRYPTION_PRIVATE_KEY=${decrypt}
`;

let existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
existing = existing.replace(/\n?# --- HBL PACO[\s\S]*?(?=\n# ---|\n[A-Z_]+=|$)/g, "\n").trimEnd();
fs.writeFileSync(envPath, `${existing}\n${block}\n`, "utf8");
console.info("Updated .env with HBL PACO UAT settings (secrets not printed).");
console.info("Office ID set:", Boolean(officeId), "| API key set:", Boolean(apiKey));
